#include <stdio.h>

int main() {
    int N;                  // 배열의 크기(원소 개수)
    int a[20], b[20];       // 두 개의 정수 배열
    int *p, *q;             // p: 배열 a 순회용 포인터, q: 배열 b 역순 순회용 포인터

    scanf("%d", &N);        // 배열의 크기 입력

    // 배열 a의 원소 입력
    for (p = a; p < a + N; p++) {
        scanf("%d", p);     // p가 가리키는 위치에 값 저장
    }

    // 배열 b의 원소 입력
    for (p = b; p < b + N; p++) {
        scanf("%d", p);     // p가 가리키는 위치에 값 저장
    }

    /*
     * p는 배열 a의 첫 번째 원소부터 순차적으로 접근
     * q는 배열 b의 마지막 원소부터 역순으로 접근
     * 각 위치의 값을 더하여 출력
     */
    p = a;              // p → a[0] (배열 a의 시작 주소)
    q = b + N - 1;      // q → b[N-1] (배열 b의 마지막 원소 주소)

    // p가 배열 a의 범위를 벗어나기 전까지 반복
    while (p < a + N) {

        // a의 현재 원소와 b의 역순 원소를 더하여 출력
        printf(" %d", *p + *q);

        p++;    // 다음 원소로 이동
        q--;    // 이전 원소로 이동 
    }

    return 0;   // 프로그램 정상 종료
}
